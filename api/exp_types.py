"""生职迹 Career Trail · 经历类型的唯一真源（后端）

经历类型贯穿全链路：录入表单 → 导入判定 → 简历板块映射 → 数据库迁移。
集中在这里，是为了让「新增一类经历」只改一处（前端对应文件：
src/types/experience.ts 的 ExpType / EXP_TYPES，改一处必须改两处）。

既有六类：
    实习 / 项目 / 校园 / 科研 / 教育 / 技能
其中「校园」= 学生工作、职务、社团与学生组织（团支书、班长、学生会、
创新创业中心…）——它们既不是实习也不是项目，单列一类才能在简历里
形成自己的「校园经历」板块。
"""
from __future__ import annotations

import re

VALID_TYPES = ("实习", "项目", "校园", "科研", "教育", "技能")

# 按「任务」拆分的类型：一件件做过的事，各自有背景 / 行动 / 结果。
# 教育 / 技能是既成事实（GPA、课程、技能名），按条目存，不拆任务。
TASK_TYPES = {"实习", "项目", "校园", "科研"}

# 校园职务 / 学生工作的关键词。
# 为什么要用规则兜底：模型看到「2021级投资学2班团支书」这种标题，
# 很容易归成 `项目`（它长得像"一段有产出的事情"），这类关键词命中后直接纠回「校园」。
CAMPUS_RE = re.compile(
    "团支书|团干|团支部|班长|班委|学生会|研究生会|团委|学生工作|社团|协会"
    "|校园大使|学生助理|辅导员|志愿者|志愿服务|社会实践|创新创业中心|学生组织"
)


def is_campus_role(*texts: str) -> bool:
    """标题 / 机构名里出现学生工作关键词 → 属于校园经历。"""
    return bool(CAMPUS_RE.search(" ".join(str(t or "") for t in texts)))
